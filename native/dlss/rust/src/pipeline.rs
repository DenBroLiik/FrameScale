//! Local Vulkan image pipeline. Synthetic test frames, not DLSS or GL interop.
//! The ring owns images and verification buffers until explicit consumer release.
use crate::{Extent,shared::{SharedImage,ImageKind,Handles},scheduler::{Scheduler,Ticket,Poll},vulkan::DeviceContext};
use ash::vk;
const LIMIT:u64=256*1024*1024;
type Result<T>=std::result::Result<T,String>;
fn err(e:impl std::fmt::Debug)->String{format!("{e:?}")}
fn pixels(e:Extent)->u64{u64::from(e.w)*u64::from(e.h)}
fn estimate(src:Extent,dst:Extent,n:usize)->Option<u64>{
    if !src.valid()||!dst.valid()||src.w>dst.w||src.h>dst.h||!(1..=4).contains(&n){return None}
    // HDR input + depth + motion, HDR output + verification buffer.
    let bytes=(pixels(src)*16+pixels(dst)*16)*n as u64;
    (bytes<=LIMIT).then_some(bytes)
}
fn rgba(frame:u32)->[f32;4]{
    [(frame%128) as f32/128.,((frame/128)%128) as f32/128.,0.5,1.]
}
// Only exact, nonnegative binary fractions in [0,1] generated by rgba().
fn half(v:f32)->u16{
    if v==0.{return 0}
    let b=v.to_bits();
    ((((b>>23)&255)-112)<<10 | ((b>>13)&1023)) as u16
}
struct Readback<'a>{
    ctx:&'a DeviceContext,buffer:vk::Buffer,memory:vk::DeviceMemory,bytes:u64,allocation:u64,coherent:bool,
}
impl<'a> Readback<'a>{
    fn new(ctx:&'a DeviceContext,bytes:u64)->Result<Self>{
        let d=ctx.raw_device();
        let mut r=Self{ctx,buffer:vk::Buffer::null(),memory:vk::DeviceMemory::null(),bytes,allocation:0,coherent:false};
        let bi=vk::BufferCreateInfo::default().size(bytes).usage(vk::BufferUsageFlags::TRANSFER_DST).sharing_mode(vk::SharingMode::EXCLUSIVE);
        r.buffer=unsafe{d.create_buffer(&bi,None)}.map_err(err)?;
        let req=unsafe{d.get_buffer_memory_requirements(r.buffer)};
        let props=unsafe{ctx.raw_instance().get_physical_device_memory_properties(ctx.physical())};
        let types=&props.memory_types[..props.memory_type_count as usize];
        let mut candidates=types.iter().enumerate().filter(|(i,m)|req.memory_type_bits&(1u32<<*i)!=0&&m.property_flags.contains(vk::MemoryPropertyFlags::HOST_VISIBLE));
        let (index,mt)=candidates.clone().find(|(_,m)|m.property_flags.contains(vk::MemoryPropertyFlags::HOST_COHERENT))
            .or_else(||candidates.next()).ok_or("no host-visible memory")?;
        r.coherent=mt.property_flags.contains(vk::MemoryPropertyFlags::HOST_COHERENT);
        r.allocation=req.size;
        let mi=vk::MemoryAllocateInfo::default().allocation_size(req.size).memory_type_index(index as u32);
        r.memory=unsafe{d.allocate_memory(&mi,None)}.map_err(err)?;
        unsafe{d.bind_buffer_memory(r.buffer,r.memory,0)}.map_err(err)?;
        Ok(r)
    }
    fn verify(&self,frame:u32)->Result<()>{
        let d=self.ctx.raw_device();
        let ptr=unsafe{d.map_memory(self.memory,0,vk::WHOLE_SIZE,vk::MemoryMapFlags::empty())}.map_err(err)?;
        let result=(||{
            if !self.coherent{
                let range=vk::MappedMemoryRange::default().memory(self.memory).size(vk::WHOLE_SIZE);
                unsafe{d.invalidate_mapped_memory_ranges(&[range])}.map_err(err)?;
            }
            let expected=rgba(frame).map(half);
            let data=unsafe{std::slice::from_raw_parts(ptr.cast::<u8>(),self.bytes as usize)};
            if !data.chunks_exact(8).all(|p|(0..4).all(|i|u16::from_ne_bytes([p[i*2],p[i*2+1]])==expected[i])){
                return Err(format!("HDR pixel mismatch for frame {frame}"))
            }
            Ok(())
        })();
        unsafe{d.unmap_memory(self.memory)};
        result
    }
}
impl Drop for Readback<'_>{
    fn drop(&mut self){unsafe{
        let d=self.ctx.raw_device();
        if self.buffer!=vk::Buffer::null(){d.destroy_buffer(self.buffer,None)}
        if self.memory!=vk::DeviceMemory::null(){d.free_memory(self.memory,None)}
    }}
}
struct Slot<'a>{
    images:[SharedImage<'a>;4],read:Readback<'a>,handles:Option<[Handles;4]>,
    frame:Option<u32>,initialized:bool,verified:bool,
}
impl Slot<'_>{
    fn allocation(&self)->u64{self.images.iter().map(|i|i.allocation_size()).sum::<u64>()+self.read.allocation}
    // All references are retired; only called after the scheduler is drained.
    fn close(self){for image in self.images{unsafe{image.close()}}}
}
#[must_use]
pub struct Pipeline<'a>{
    ctx:&'a DeviceContext,scheduler:Scheduler<'a>,slots:Vec<Slot<'a>>,
    src:Extent,dst:Extent,allocation:u64,closed:bool,
}
impl<'a> Pipeline<'a>{
    pub fn new(ctx:&'a DeviceContext,src:Extent,dst:Extent,n:usize)->Result<Self>{
        estimate(src,dst,n).ok_or("invalid extent, slot count or memory budget")?;
        let features=unsafe{ctx.raw_instance().get_physical_device_format_properties(ctx.physical(),vk::Format::R16G16B16A16_SFLOAT)}.optimal_tiling_features;
        if !features.contains(vk::FormatFeatureFlags::BLIT_SRC|vk::FormatFeatureFlags::BLIT_DST){return Err("HDR blit unsupported".into())}
        let mut slots=Vec::with_capacity(n);let mut allocation=0u64;
        for _ in 0..n{
            let slot=Slot{
                images:[
                    SharedImage::local(ctx,src,ImageKind::HdrInput).map_err(err)?,
                    SharedImage::local(ctx,src,ImageKind::DepthCopy).map_err(err)?,
                    SharedImage::local(ctx,src,ImageKind::Motion).map_err(err)?,
                    SharedImage::local(ctx,dst,ImageKind::HdrOutput).map_err(err)?,
                ],
                read:Readback::new(ctx,pixels(dst)*8)?,handles:None,frame:None,initialized:false,verified:false,
            };
            allocation=allocation.checked_add(slot.allocation()).ok_or("allocation overflow")?;
            if allocation>LIMIT{return Err("actual image/buffer allocation budget exceeded".into())}
            slots.push(slot);
        }
        let scheduler=Scheduler::new(ctx,n).map_err(err)?;
        Ok(Self{ctx,scheduler,slots,src,dst,allocation,closed:false})
    }
    pub fn allocation_size(&self)->u64{self.allocation}
    /// None means all slots remain owned by GPU or consumer. No explicit CPU wait.
    pub fn submit(&mut self,frame:u32)->Result<Option<Ticket>>{
        let Some((ticket,cmd))=self.scheduler.try_begin().map_err(err)? else{return Ok(None)};
        let slot=&mut self.slots[ticket.index()];
        if slot.handles.is_none(){slot.handles=Some(slot.images.each_mut().map(|i|i.handles()));}
        let handles=slot.handles.expect("initialized handles");
        let d=self.ctx.raw_device();
        let range=vk::ImageSubresourceRange::default().aspect_mask(vk::ImageAspectFlags::COLOR).level_count(1).layer_count(1);
        let layers=vk::ImageSubresourceLayers::default().aspect_mask(vk::ImageAspectFlags::COLOR).layer_count(1);
        let old=if slot.initialized{vk::ImageLayout::GENERAL}else{vk::ImageLayout::UNDEFINED};
        let prior=if slot.initialized{vk::AccessFlags::TRANSFER_READ|vk::AccessFlags::TRANSFER_WRITE}else{vk::AccessFlags::empty()};
        let start=if slot.initialized{vk::PipelineStageFlags::TRANSFER}else{vk::PipelineStageFlags::TOP_OF_PIPE};
        let barrier=|h:Handles,old,src,dst|vk::ImageMemoryBarrier::default().image(h.image).subresource_range(range)
            .old_layout(old).new_layout(vk::ImageLayout::GENERAL).src_access_mask(src).dst_access_mask(dst)
            .src_queue_family_index(vk::QUEUE_FAMILY_IGNORED).dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED);
        let begin=handles.map(|h|barrier(h,old,prior,vk::AccessFlags::TRANSFER_WRITE));
        let color=vk::ClearColorValue{float32:rgba(frame)};
        let depth=vk::ClearColorValue{float32:[0.5,0.,0.,0.]};
        let motion=vk::ClearColorValue{float32:[0.;4]};
        let blit=vk::ImageBlit::default().src_subresource(layers).dst_subresource(layers)
            .src_offsets([vk::Offset3D::default(),vk::Offset3D{x:self.src.w as i32,y:self.src.h as i32,z:1}])
            .dst_offsets([vk::Offset3D::default(),vk::Offset3D{x:self.dst.w as i32,y:self.dst.h as i32,z:1}]);
        let copy=vk::BufferImageCopy::default().image_subresource(layers)
            .image_extent(vk::Extent3D{width:self.dst.w,height:self.dst.h,depth:1});
        let host=vk::BufferMemoryBarrier::default().src_access_mask(vk::AccessFlags::TRANSFER_WRITE)
            .dst_access_mask(vk::AccessFlags::HOST_READ).src_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
            .dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED).buffer(slot.read.buffer).size(vk::WHOLE_SIZE);
        unsafe{
            d.cmd_pipeline_barrier(cmd,start,vk::PipelineStageFlags::TRANSFER,vk::DependencyFlags::empty(),&[],&[],&begin);
            for (h,value) in handles[..3].iter().zip([color,depth,motion]){
                d.cmd_clear_color_image(cmd,h.image,vk::ImageLayout::GENERAL,&value,&[range]);
            }
            let ready=barrier(handles[0],vk::ImageLayout::GENERAL,vk::AccessFlags::TRANSFER_WRITE,vk::AccessFlags::TRANSFER_READ);
            d.cmd_pipeline_barrier(cmd,vk::PipelineStageFlags::TRANSFER,vk::PipelineStageFlags::TRANSFER,vk::DependencyFlags::empty(),&[],&[],&[ready]);
            d.cmd_blit_image(cmd,handles[0].image,vk::ImageLayout::GENERAL,handles[3].image,vk::ImageLayout::GENERAL,&[blit],vk::Filter::NEAREST);
            let ready=barrier(handles[3],vk::ImageLayout::GENERAL,vk::AccessFlags::TRANSFER_WRITE,vk::AccessFlags::TRANSFER_READ);
            d.cmd_pipeline_barrier(cmd,vk::PipelineStageFlags::TRANSFER,vk::PipelineStageFlags::TRANSFER,vk::DependencyFlags::empty(),&[],&[],&[ready]);
            d.cmd_copy_image_to_buffer(cmd,handles[3].image,vk::ImageLayout::GENERAL,slot.read.buffer,&[copy]);
            d.cmd_pipeline_barrier(cmd,vk::PipelineStageFlags::TRANSFER,vk::PipelineStageFlags::HOST,vk::DependencyFlags::empty(),&[],&[host],&[]);
            self.scheduler.submit(ticket,&[],&[],&[]).map_err(err)?;
        }
        slot.initialized=true;slot.frame=Some(frame);slot.verified=false;
        Ok(Some(ticket))
    }
    pub fn poll(&mut self,t:Ticket)->Result<Poll>{self.scheduler.poll(t).map_err(err)}
    /// Diagnostic consumer: verifies every output pixel after fence completion.
    pub fn verify(&mut self,t:Ticket)->Result<bool>{
        if self.poll(t)?!=Poll::Ready{return Ok(false)}
        let slot=&mut self.slots[t.index()];
        slot.read.verify(slot.frame.ok_or("missing frame")?)?;
        slot.verified=true;Ok(true)
    }
    pub fn release(&mut self,t:Ticket)->Result<()>{
        if self.poll(t)?!=Poll::Ready{return Err("GPU not retired".into())}
        let slot=&mut self.slots[t.index()];
        if !slot.verified{return Err("consumer has not verified the frame".into())}
        unsafe{self.scheduler.release(t)}.map_err(err)?;
        slot.frame=None;slot.verified=false;Ok(())
    }
    pub fn close(&mut self)->Result<()>{
        self.scheduler.close().map_err(err)?;
        for slot in self.slots.drain(..){slot.close()}
        self.closed=true;Ok(())
    }
}
impl Drop for Pipeline<'_>{
    fn drop(&mut self){
        // Scheduler may still own pending work. Never free exposed images or
        // verification buffers here; process must exit after a fatal error.
        if !self.closed{for slot in self.slots.drain(..){std::mem::forget(slot)}}
    }
}
#[cfg(test)]
mod tests{
    use super::*;
    #[test]fn budget(){
        assert_eq!(estimate(Extent{w:32,h:24},Extent{w:64,h:48},3),Some(184320));
        assert!(estimate(Extent{w:4096,h:4096},Extent{w:4096,h:4096},4).is_none());
        assert!(estimate(Extent{w:64,h:48},Extent{w:32,h:24},1).is_none());
    }
    #[test]fn exact_half(){
        assert_eq!(half(0.),0);assert_eq!(half(0.5),0x3800);assert_eq!(half(1.),0x3c00);
        assert_eq!(half(1./128.),0x2000);assert_ne!(rgba(1).map(half),rgba(2).map(half));
    }
}
